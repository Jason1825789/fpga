//====================================================
// font_rom.v — OSD 字模 ROM(字幕引擎字库)
// 功能: 输入字符位置号(0~13)+ 字符内行列号(0~15), 输出笔画/描边
// 生成工具: python/font2verilog.py(雅黑粗体 2x渲染+腐蚀 = 中等粗细 2px,
//           + 倾斜 + 紧凑左对齐)
// 【位序约定, 写错字会上下颠倒】
//   字面量里"最右边那一组"对应 bits[15:0], 也就是 row=0 的那一行(字符最上行);
//   每行 16 位里 bit15 = 最左列
//====================================================
module font_rom(
    input  wire [3:0]  char_sel,   // 字符位置号 0~13(见下方映射表)
    input  wire [4:0]  row,        // 字符内行号 0~15
    input  wire [4:0]  col,        // 字符内列号 0~15
    output wire        pixel_on,   // 1=笔画(显示字色) 0=空白
    output wire        outline_on  // 1=描边(笔画相邻 1 像素,8 邻域)
);

// 字幕串: "2026FPGA创新设计竞赛" 共 14 字符
// 位置号 → 字符 映射(重复字符共用一套字模):
//   0:'2'  1:'0'  2:'2'  3:'6'  4:'F'  5:'P'  6:'G'  7:'A'
//   8:'创' 9:'新' 10:'设' 11:'计' 12:'竞' 13:'赛'
function [3:0] pos_to_font;
    input [3:0] pos;
    begin
        case (pos)
            4'd0 : pos_to_font = 4'd0;    // '2'
            4'd1 : pos_to_font = 4'd1;    // '0'
            4'd2 : pos_to_font = 4'd0;    // '2'
            4'd3 : pos_to_font = 4'd2;    // '6'
            4'd4 : pos_to_font = 4'd3;    // 'F'
            4'd5 : pos_to_font = 4'd4;    // 'P'
            4'd6 : pos_to_font = 4'd5;    // 'G'
            4'd7 : pos_to_font = 4'd6;    // 'A'
            4'd8 : pos_to_font = 4'd7;    // '创'
            4'd9 : pos_to_font = 4'd8;    // '新'
            4'd10: pos_to_font = 4'd9;    // '设'
            4'd11: pos_to_font = 4'd10;   // '计'
            4'd12: pos_to_font = 4'd11;   // '竞'
            default: pos_to_font = 4'd12; // '赛'
        endcase
    end
endfunction

// ============ 备用字库(当前不显示,以后可调用) ============
localparam [255:0] FONT_WAN   = 256'h0000_4000_61F0_3018_1808_0808_0C08_0408_040C_040C_07FC_0400_0600_0600_FFFF_0000;   // '万'
localparam [255:0] FONT_XIANG = 256'h0000_4780_30C2_0C44_6348_1CD0_66F0_1D98_0704_3FFE_2186_A086_7FFE_1020_0FF0_0400;   // '象'
localparam [255:0] FONT_PING  = 256'h0000_0000_8C10_4610_6210_3FFF_2310_2310_2FFE_2110_2210_3FFE_2002_2002_3FFE_0000;   // '屏'

// ============ 主字库:13 套字模打包(最右一组 = 编号 0) ============
// 字体: 思源黑体(NotoSansSC-VF,字重500)+ 倾斜 + 紧凑(数字/字母左对齐收窄间距)
// 注意:Verilog 数字字面量不可跨行,整串必须写在一行
localparam [3327:0] FONT_ALL = 3328'h0000_0000_7806_0E3C_09F8_0888_2C0C_3FFF_0E1C_3FFF_0330_03B8_0FFE_1001_1FFF_0060_0000_0000_707E_1C66_0662_0260_0FFC_0C0C_0804_0FFC_0000_3FFF_071C_0208_0FFF_0060_0000_2060_7060_3860_1C60_1020_1020_1830_1830_7BFF_79FE_0010_0010_0C10_1818_0018_0000_0000_671E_31F8_38E0_38F0_1188_1104_13FE_1804_7A00_7B87_0084_04C4_0C4C_187C_0000_0000_1884_0884_69C4_2FC4_0466_3FE6_0426_0422_3FFF_1FF0_0930_09B0_1FFC_0207_0000_3F38_210C_2004_2604_3326_3126_31A6_3FA2_60B2_30F2_1893_0D93_0713_0703_0201_0000_0000_0000_0000_6060_2060_3060_18E0_1FE0_0CC0_0CC0_0CC0_06C0_03C0_0380_0180_0000_0000_0000_0000_1F00_3F80_6080_60C0_60C0_63C0_61C0_6000_3000_3800_1FC0_0780_0000_0000_0000_0000_6000_6000_6000_3000_3800_3F80_31C0_30C0_30C0_10C0_1FC0_1F80_0000_0000_0000_0000_6000_6000_6000_3000_3000_3F00_3F00_3000_3000_1000_1F80_1FC0_0000_0000_0000_0000_1C00_7E00_6300_6180_6180_7380_7F00_6000_3000_3000_1F80_0700_0000_0000_0000_0000_3C00_7E00_6300_6300_6180_6180_6180_6180_2180_3180_1F80_0F00_0000_0000_0000_0000_7F80_3B80_1800_0C00_0600_0300_0180_0180_0180_0180_1F80_0F00;

// ① 位置号 → 字库编号(串里重复的字共用一套字模)
wire [3:0] font_idx = pos_to_font(char_sel);
// ② 选出该字的 256 位字模(编号×256 = {编号, 8'b0} 作为位选基址)
wire [255:0] font_bits = FONT_ALL[{font_idx, 8'b00000000} +: 256];

// ③ 邻居坐标(边界钳位,防索引越界)
wire [4:0] r_up    = (row == 5'd0)  ? 5'd0  : row - 5'd1;
wire [4:0] r_down  = (row == 5'd15) ? 5'd15 : row + 5'd1;
wire [4:0] c_left  = (col == 5'd0)  ? 5'd0  : col - 5'd1;
wire [4:0] c_right = (col == 5'd15) ? 5'd15 : col + 5'd1;

// ④ 三行切片(当前/上一/下一行)
wire [15:0] fr_cur  = font_bits[{row,    4'b0000} +: 16];
wire [15:0] fr_up   = font_bits[{r_up,   4'b0000} +: 16];
wire [15:0] fr_down = font_bits[{r_down, 4'b0000} +: 16];

// ⑤ 笔画本身
assign pixel_on = fr_cur[15 - col];

// ⑥ 描边:自身不是笔画,但 8 邻域里有笔画
assign outline_on = ~pixel_on & (
    fr_up[15 - col]      | fr_down[15 - col] |       // 上 / 下
    fr_cur[15 - c_left]  | fr_cur[15 - c_right] |    // 左 / 右
    fr_up[15 - c_left]   | fr_up[15 - c_right] |     // 左上 / 右上
    fr_down[15 - c_left] | fr_down[15 - c_right]      // 左下 / 右下
);

endmodule
