// 刷新开关说明（2026-10-31）：
//   该控制器（sdr_as_ram）的硬件自刷新路径在本工程中实测不可用——
//     · self_refresh_open=1 按 JEDEC 标准间隔(31.25us)发 REF：读数据被污染，
//       画面每张图都出现横向彩色条（已用 A/B 比特流上板确认，关掉即干净）
//     · 把刷新周期降到 1/64 后 REF 仍会与写通道的突发相撞，导致 SDRAM 仲裁
//       挂死、切一张图后按键全部无响应
//   因此这里关闭硬件刷新，改由 sd_card_bmp 的"保鲜重写"机制维持数据：
//   每 5 秒把备用缓冲里的同一张图原样重写一遍（见 SD/sd_card_bmp.v）。
//   global_def.v 里的 SELF_REFRESH_INTERVAL 仍保持 JEDEC 正确值 3906，
//   仅作为记录，不参与工作。
sdr_as_ram  #( .self_refresh_open(1'b0))
	u2_ram( 
		.Sdr_clk(Clk),
		.Sdr_clk_sft(Clk_sft),
		.Rst(Rst),
			  			  
		.Sdr_init_done(Sdr_init_done),
		.Sdr_init_ref_vld(Sdr_init_ref_vld),
		.Sdr_busy(Sdr_busy),
		
		.App_ref_req(1'b0),
		
        .App_wr_en(App_wr_en), 
        .App_wr_addr(App_wr_addr),  	
		.App_wr_dm(App_wr_dm),
		.App_wr_din(App_wr_din),

		.App_rd_en(App_rd_en),
		.App_rd_addr(App_rd_addr),
		.Sdr_rd_en	(Sdr_rd_en),
		.Sdr_rd_dout(Sdr_rd_dout),
	
		.SDRAM_CLK(SDRAM_CLK),
		.SDR_RAS(SDR_RAS),
		.SDR_CAS(SDR_CAS),
		.SDR_WE(SDR_WE),
		.SDR_BA(SDR_BA),
		.SDR_ADDR(SDR_ADDR),
		.SDR_DM(SDR_DM),
		.SDR_DQ(SDR_DQ)	
	);


