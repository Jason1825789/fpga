//============================================================================
// spectrum_overlay.v -- 把柱高画到像素上（纯组合，无时钟）
//
// 每根柱占 8 像素：前 6 像素画柱体，后 2 像素留间隙。
// 柱号直接取 pixel_x[9:3]（0..79），不需要除 10 之类的除法器。
//
// 位置约束（都是实测已有的图元，不能压）：
//   底部红条 y=460..479、滚动字幕 y=462..478、左上状态条 y=0..24
//   → 柱底取 y=459（正好坐在红条上沿 460 之上，紧贴不留缝）。
//
// 显示高度：★ 在这里做 ×5/8 缩放，bar_h 的语义（0..240）保持不变。
//   实测 C4~C5 八个音的峰值柱高 175~184，最高 177px 从 y=282 就起笔，
//   把画面主体压住了（遮挡 38%）。缩到 5/8 后最高 110px、遮挡 23%，
//   柱区收缩到屏幕下半部分。
//   ★ 为什么放在 overlay 而不是 engine：
//     一旦改 engine，bars[] 的单位就从"240 满量程"变成"150"，必须同步改
//     BAR_TOP、明度截距和 verification/gen_stim.py 的黄金模型，四处联动，
//     漏一处就出错。放在这里则 engine 一行不动、黄金模型不用重新生成，
//     run_spectrum.py 的回归结果应当与改动前逐位相同——这本身就是一道校验。
//   ★ 明度仍用**原始 bar_h**，不用 h_disp：
//     明度表示"这根柱有多强"，与"它在屏幕上多高"是两件事。若跟着缩放，
//     柱高范围从 59~177 塌到 37~110，明暗差会从 1.6 倍缩到 1.35 倍，
//     正好重演之前"明度变化看不出来"的错误。用原始值则对比度完全不变。
//   5/8 = 1/2 + 1/8，两次右移一次加法，不加乘法器。
//
// 配色：★ 色相跟着【柱号】走，不是跟着【柱高】走。
//   参考 aystmjz/Music-Spectrum、VrchStudio、cli-viz 等实现，主流做法都是
//   "hue from frequency(bar index), brightness/value from amplitude"。
//   早期版本按柱高取色，实测柱高集中在 100~176 这一段，只用到色表 3~4 级，
//   屏上看起来几乎全是绿的一色；改成按柱号后 80 根柱铺满整个色相范围，
//   形成一条彩虹横带，高度起伏叠在上面，变化一眼可辨。
//   索引 = pixel_x[9:5]（0..19），每 4 根柱一档，正好覆盖 20 档 x 4 = 80 根。
//
// 明度：★ 色相管"在哪根柱"，明度管"柱有多高"。
//   两者正交，是本文件最核心的一条设计约束：
//     色相 = f(pixel_x)  —— 横轴上铺满彩虹，一帧内恒定，柱跳不变色
//     明度 = g(bar_h)    —— 低柱压暗、高柱接近满亮，高度信息立起来
//   g 取线性 k = 96 + bar_h（饱和于 255），即 38%~100%，用一次 8x8 乘法实现。
//   斜率取 1:1 是被实测柱高分布（59~184）逼出来的，小斜率会让明暗差被压到看不见。
//   比"8 级移位加法"（约 120 LUT/通道）便宜一个量级，且没有可见台阶。
//
// 柱顶 3 像素用暖白高亮，视觉上充当"峰值线"。
//   ★ 没有做真正的历史峰值保持：它要额外存 80 根 x 8bit，并且要在像素通路
//     按柱号读出，会再生成一个 640 位读多路器，和 bars[] 那个把布线挤爆的
//     结构同类。真正的峰值保持留到"bars 改同步读"那一轮一起做。
//   ★ 暖白不参与明度调制：低柱柱身很暗、柱顶仍是亮白，对比更强，峰值线更醒目。
//============================================================================
module spectrum_overlay (
    input  wire [15:0] pixel_x,
    input  wire [15:0] pixel_y,
    input  wire [7:0]  bar_h,
    input  wire [23:0] bg_pixel,
    output wire [23:0] out_pixel
);

    localparam [15:0] BAR_BOTTOM = 16'd459;    // 柱底（含），紧贴底部红条上沿 460
    localparam [15:0] BAR_TOP    = 16'd309;    // 绘制窗下界（150 像素高 = 240 x 5/8）
    localparam [2:0]  BAR_W      = 3'd6;       // 每格画 6 像素
    localparam [15:0] PEAK_H     = 16'd3;      // 柱顶高亮高度（像素）
    localparam [23:0] COL_PEAK   = 24'hFFF8E0; // 暖白

    // 显示高度 = bar_h x 5/8（= 1/2 + 1/8），0..240 -> 0..150
    //   11 位中间量：240*5 = 1200 < 2048，不会溢出
    wire [10:0] h5     = {3'b0, bar_h} + {1'b0, bar_h, 2'b00};
    wire [7:0]  h_disp = h5[10:3];

    // ------------------------------------------------------------------
    // 20 档彩虹，索引取 pixel_x[9:5]（0..19）：色相 10°->200°
    //   低频(左) 红橙 -> 黄 -> 绿 -> 青 -> 蓝(右)
    // 饱和度 0.85 / 明度 0.96，压掉了纯色的割裂感，照片上也不刺眼。
    // 索引只和横坐标有关，与 bar_h 完全解耦，因此颜色在一帧内是稳定的，
    // 柱子上下跳动时不会"变色"，观感更干净。
    // ------------------------------------------------------------------
    function [23:0] rainbow;
        input [4:0] i;
        begin
            case (i)
                5'd0 : rainbow = 24'hF54725;
                5'd1 : rainbow = 24'hF56A25;
                5'd2 : rainbow = 24'hF58D25;
                5'd3 : rainbow = 24'hF5AF25;
                5'd4 : rainbow = 24'hF5D225;
                5'd5 : rainbow = 24'hF5F525;
                5'd6 : rainbow = 24'hD2F525;
                5'd7 : rainbow = 24'hAFF525;
                5'd8 : rainbow = 24'h8DF525;
                5'd9 : rainbow = 24'h6AF525;
                5'd10: rainbow = 24'h47F525;
                5'd11: rainbow = 24'h25F525;
                5'd12: rainbow = 24'h25F547;
                5'd13: rainbow = 24'h25F56A;
                5'd14: rainbow = 24'h25F58D;
                5'd15: rainbow = 24'h25F5AF;
                5'd16: rainbow = 24'h25F5D2;
                5'd17: rainbow = 24'h25F5F5;
                5'd18: rainbow = 24'h25D2F5;
                default: rainbow = 24'h25AFF5;
            endcase
        end
    endfunction

    wire        in_x    = (pixel_x < 16'd640);
    wire        in_cell = (pixel_x[2:0] < BAR_W);
    wire        in_y    = (pixel_y <= BAR_BOTTOM) && (pixel_y >= BAR_TOP);
    wire [15:0] dy      = BAR_BOTTOM - pixel_y;      // in_y 成立时必在 0..150
    wire        hit     = in_x && in_cell && in_y && (dy < {8'd0, h_disp});

    // 柱顶高亮：距柱底不足 PEAK_H 像素的位置即为柱顶
    // h_disp=100 时 dy=97..99 命中，正好 3 行
    wire        is_peak = ((dy + PEAK_H) >= {8'd0, h_disp});

    // 色相索引只与横坐标有关（每 4 根柱一档），与柱高无关
    wire [23:0] bar_color = rainbow(pixel_x[9:5]);

    // ------------------------------------------------------------------
    // 明度系数 k = 96 + bar_h，饱和于 255
    //   ★ 注意这里用的是**原始 bar_h**，不是 h_disp。
    //     明度表达"这根柱有多强"，显示高度表达"它在屏幕上多高"，两者正交。
    //     若改用 h_disp（37~110），明暗差会从 1.6 倍塌到 1.35 倍，
    //     重演之前"明度变化看不出来"的错误。这里保持原值，缩放不影响色彩层次。
    //   斜率刻意取 1:1（柱高每涨 1 像素，明度系数就涨 1），原因是实测柱高
    //   分布很集中：C4~C5 八个音的柱高只在 59~184 之间，跨度 125 像素。
    //   若用 k=160+3*bar_h/8 这类小斜率，这段只映射出 182~226，亮度差 24%，
    //   肉眼几乎看不出——和之前"颜色变化不明显"是同一类错误。
    //   取 1:1 后：h=60 -> 61%，h=100 -> 77%，h=159 -> 100%（饱和）。
    //   只有 h>=159 的高柱会顶格，正好落在峰值柱附近，观感上是"最高的柱最亮"。
    //   9 位中间量避免溢出，饱和用最高位判断，不需要比较器。
    //   范围校验：色值最大 0xF5=245，245*255 = 62475 < 65535，16 位不溢出。
    // ------------------------------------------------------------------
    wire [8:0] k9     = 9'd96 + {1'b0, bar_h};
    wire [7:0] bright = k9[8] ? 8'd255 : k9[7:0];

    // 通道值 x 明度系数 / 256：一次 8x8 乘法，线性、无台阶
    //   ⚠ Verilog 的乘法结果位宽 = max(操作数位宽)，两个 8 位相乘**仍然只有 8 位**，
    //     直接写 (c*k)>>8 会先溢出截断再右移，结果恒为 0。
    //     必须赋给 16 位变量，让表达式上下文把位宽撑开。
    function [7:0] dim;
        input [7:0] c;
        input [7:0] k;
        reg   [15:0] p;
        begin
            p   = c * k;
            dim = p[15:8];
        end
    endfunction

    wire [23:0] bar_dim = { dim(bar_color[23:16], bright),
                            dim(bar_color[15:8],  bright),
                            dim(bar_color[7:0],   bright) };

    // ------------------------------------------------------------------
    // ★ 不再与底图做半透明混合，直接输出调暗后的柱色。
    //   上一版是 "75% 柱色 + 25% 底图"，看起来通透，但它会**压缩明度动态范围**：
    //   暗端被亮照片"抬起"，低柱永远压不下去，明度调制做完仍是一屏差不多亮。
    //   实测 12.5% 背景时柱高 24->240 的亮度只差 1.5 倍，去掉后 1.6 倍且暗端更低。
    //   柱子只占每格 8px 中的 6px、且只在自身高度内点亮，照片其余部分不受影响。
    // ------------------------------------------------------------------

    // 柱顶高亮直接用纯色，保证在任何画面上都能看清
    assign out_pixel = !hit    ? bg_pixel :
                       is_peak ? COL_PEAK : bar_dim;

endmodule
