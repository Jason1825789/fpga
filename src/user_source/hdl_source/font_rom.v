//====================================================
// font_rom.v — OSD 字模 ROM(字幕引擎字库)
// 功能: 输入字符位置号 + 文案选择 + 字符内行列号(0~15), 输出笔画/描边
// 生成工具: python/font2verilog.py(由文案自动生成)
//           64x64 灰度渲染 → LANCZOS 缩回 16x16 → 阈值二值化
//           无腐蚀 / 无倾斜
//           ASCII 按基线对齐(标点位置正确), 汉字按字框顶对齐
// 【位序约定, 写错字会上下颠倒】
//   字面量里"最右边那一组"对应 bits[15:0], 也就是 row=0 的那一行(字符最上行);
//   每行 16 位里 bit15 = 最左列
//====================================================
module font_rom(
    input  wire [3:0]  char_sel,   // 字符位置号 0~15(见下方映射表)
    input  wire        txt_sel,    // 0 = 文案A(开园句), 1 = 文案B(闭园句)
    input  wire [4:0]  row,        // 字符内行号 0~15
    input  wire [4:0]  col,        // 字符内列号 0~15
    output wire        pixel_on,   // 1=笔画(显示字色) 0=空白
    output wire        outline_on  // 1=描边(笔画相邻 1 像素,8 邻域)
);

// 文案A(txt_sel=0): "9:00-17:00颐和园欢迎您"  16 字符 = 10 ASCII + 6 汉字
// 文案B(txt_sel=1): "17:00-9:00颐和园已闭园"  16 字符 = 10 ASCII + 6 汉字
// 两句排版完全相同(10x12 + 6x16 = 216px)，共用同一套字库
//
// 位置号 → 字符(文案A):
//   0: '9'
//   1: ':'
//   2: '0'
//   3: '0'
//   4: '-'
//   5: '1'
//   6: '7'
//   7: ':'
//   8: '0'
//   9: '0'
//   10: '颐'
//   11: '和'
//   12: '园'
//   13: '欢'
//   14: '迎'
//   15: '您'
//
// 位置号 → 字符(文案B):
//   0: '1'
//   1: '7'
//   2: ':'
//   3: '0'
//   4: '0'
//   5: '-'
//   6: '9'
//   7: ':'
//   8: '0'
//   9: '0'
//   10: '颐'
//   11: '和'
//   12: '园'
//   13: '已'
//   14: '闭'
//   15: '园'
//
// 独立字模 14 套:
//    0 = '9' (ASCII, 45 px)
//    1 = ':' (ASCII, 13 px)
//    2 = '0' (ASCII, 47 px)
//    3 = '-' (ASCII, 5 px)
//    4 = '1' (ASCII, 34 px)
//    5 = '7' (ASCII, 34 px)
//    6 = '颐' (汉字, 115 px)
//    7 = '和' (汉字, 115 px)
//    8 = '园' (汉字, 132 px)
//    9 = '欢' (汉字, 82 px)
//   10 = '迎' (汉字, 118 px)
//   11 = '您' (汉字, 105 px)
//   12 = '已' (汉字, 95 px)
//   13 = '闭' (汉字, 103 px)
function [3:0] pos_to_font;
    input [3:0] pos;
    input       txt_sel;
    begin
        case ({txt_sel, pos})
        // ---- txt_sel=0: 文案A ----
        5'd0 : pos_to_font = 4'd0;   // A 位置0 = '9'
        5'd1 : pos_to_font = 4'd1;   // A 位置1 = ':'
        5'd2 : pos_to_font = 4'd2;   // A 位置2 = '0'
        5'd3 : pos_to_font = 4'd2;   // A 位置3 = '0'
        5'd4 : pos_to_font = 4'd3;   // A 位置4 = '-'
        5'd5 : pos_to_font = 4'd4;   // A 位置5 = '1'
        5'd6 : pos_to_font = 4'd5;   // A 位置6 = '7'
        5'd7 : pos_to_font = 4'd1;   // A 位置7 = ':'
        5'd8 : pos_to_font = 4'd2;   // A 位置8 = '0'
        5'd9 : pos_to_font = 4'd2;   // A 位置9 = '0'
        5'd10: pos_to_font = 4'd6;   // A 位置10 = '颐'
        5'd11: pos_to_font = 4'd7;   // A 位置11 = '和'
        5'd12: pos_to_font = 4'd8;   // A 位置12 = '园'
        5'd13: pos_to_font = 4'd9;   // A 位置13 = '欢'
        5'd14: pos_to_font = 4'd10;   // A 位置14 = '迎'
        5'd15: pos_to_font = 4'd11;   // A 位置15 = '您'
        // ---- txt_sel=1: 文案B ----
        5'd16: pos_to_font = 4'd4;   // B 位置0 = '1'
        5'd17: pos_to_font = 4'd5;   // B 位置1 = '7'
        5'd18: pos_to_font = 4'd1;   // B 位置2 = ':'
        5'd19: pos_to_font = 4'd2;   // B 位置3 = '0'
        5'd20: pos_to_font = 4'd2;   // B 位置4 = '0'
        5'd21: pos_to_font = 4'd3;   // B 位置5 = '-'
        5'd22: pos_to_font = 4'd0;   // B 位置6 = '9'
        5'd23: pos_to_font = 4'd1;   // B 位置7 = ':'
        5'd24: pos_to_font = 4'd2;   // B 位置8 = '0'
        5'd25: pos_to_font = 4'd2;   // B 位置9 = '0'
        5'd26: pos_to_font = 4'd6;   // B 位置10 = '颐'
        5'd27: pos_to_font = 4'd7;   // B 位置11 = '和'
        5'd28: pos_to_font = 4'd8;   // B 位置12 = '园'
        5'd29: pos_to_font = 4'd12;   // B 位置13 = '已'
        5'd30: pos_to_font = 4'd13;   // B 位置14 = '闭'
        5'd31: pos_to_font = 4'd8;   // B 位置15 = '园'
        default: pos_to_font = 4'd8; // B 位置15 = '园'
        endcase
    end
endfunction

// ============ 备用字库(当前不显示,以后可调用) ============
localparam [255:0] FONT_WAN   = 256'h0000_4000_61F0_3018_1808_0808_0C08_0408_040C_040C_07FC_0400_0600_0600_FFFF_0000;   // '万'
localparam [255:0] FONT_XIANG = 256'h0000_4780_30C2_0C44_6348_1CD0_66F0_1D98_0704_3FFE_2186_A086_7FFE_1020_0FF0_0400;   // '象'
localparam [255:0] FONT_PING  = 256'h0000_0000_8C10_4610_6210_3FFF_2310_2310_2FFE_2110_2210_3FFE_2002_2002_3FFE_0000;   // '屏'

// ============ 主字库: 14 套字模打包(最右一组 = 编号 0) ============
// 生成: font2verilog.py — 思源黑体(NotoSansSC-VF.ttf) 字重500
//       64x64 灰度渲染 → LANCZOS 缩回 16x16 → 阈值 > 110 二值化
//       ASCII 11x12 盒(基线对齐) / 汉字 15x15 盒(顶对齐), 均 1px 左边距
//       编号 0~11 = 原单句字库(逐位未变), 12~13 = 闭园句新增的 '已' '闭'
// 注意:Verilog 数字字面量不可跨行,整串必须写在一行
localparam [3583:0] FONT_ALL = 3584'h0000_600c_618e_63c6_7846_6c46_6646_63c6_61c6_6ff6_6ff6_6046_0046_1006_37fe_2000_0000_0ff8_3ffe_3007_3003_3003_3000_3000_301c_3ffc_300c_300c_200c_000c_7ffc_7ffc_0000_03f0_67fb_340b_3466_14c6_00c0_1870_1b33_19b6_19b4_7a34_3b12_19ff_0dfe_0480_0000_21fe_67ff_3c10_1830_1b36_1bf3_1b73_1b33_7b33_0333_0333_0b33_3b3f_23fe_00c0_0000_0000_0183_61c6_324c_1e68_1c38_0c30_1c30_16b0_37b6_22c2_02fe_7e7e_0040_0040_0000_6003_7fff_6003_787b_6c6f_664b_6643_6243_7ffb_6003_6003_6ff3_6003_7fff_7fff_0000_0c00_0c63_0c7f_6c7f_2c63_3de3_1f63_0e63_0c63_7fe3_0c63_0c63_2c7f_3f7e_0300_0000_00c0_7fe7_7f3c_4430_4452_4e5a_5e5a_525a_525a_5a52_5e42_4c7e_4418_6e18_7fff_0000_0000_0000_0000_1800_1800_1800_0800_0c00_0c00_0c00_0600_0600_0300_7f80_7f00_0000_0000_0000_0000_7f00_7e00_1800_1800_1800_1800_1800_1800_1800_3800_3800_0800_0000_0000_0000_0000_0000_0000_0000_0000_1f00_0000_0000_0000_0000_0000_0000_0000_0000_0000_0000_0000_1e00_3700_6300_6100_6180_6180_6180_6100_6300_3300_3e00_1c00_0000_0000_0000_0000_0e00_0e00_0000_0000_0000_0000_0e00_0e00_0400_0000_0000_0000_0000_0000_0000_0000_3c00_2600_0300_0300_1900_3f80_6380_6100_6300_6300_3e00_1c00;

// ① 位置号 → 字库编号(串里重复的字共用一套字模;txt_sel 选开园/闭园句)
wire [3:0] font_idx = pos_to_font(char_sel, txt_sel);
// ② 选出该字的 256 位字模(编号×256 = {编号, 8'b0} 作为位选基址)
wire [255:0] font_bits = FONT_ALL[{font_idx, 8'b00000000} +: 256];

// ③ 邻居坐标(边界钳位,防索引越界)
wire [4:0] r_up    = (row == 5'd0)  ? 5'd0  : row - 5'd1;
wire [4:0] r_down  = (row == 5'd15) ? 5'd15 : row + 5'd1;
wire [4:0] c_left  = (col == 5'd0)  ? 5'd0  : col - 5'd1;
wire [4:0] c_right = (col == 5'd15) ? 5'd15 : col + 5'd1;

// ④ 三行切片(当前/上一/下一行)
wire [15:0] fr_cur  = font_bits[{row,    4'b0000} +: 16];
wire [15:0] fr_up   = font_bits[{r_up,   4'b0000} +: 16];
wire [15:0] fr_down = font_bits[{r_down, 4'b0000} +: 16];

// ⑤ 笔画本身
assign pixel_on = fr_cur[15 - col];

// ⑥ 描边:自身不是笔画,但 8 邻域里有笔画
assign outline_on = ~pixel_on & (
    fr_up[15 - col]      | fr_down[15 - col] |       // 上 / 下
    fr_cur[15 - c_left]  | fr_cur[15 - c_right] |    // 左 / 右
    fr_up[15 - c_left]   | fr_up[15 - c_right] |     // 左上 / 右上
    fr_down[15 - c_left] | fr_down[15 - c_right]      // 左下 / 右下
);

endmodule
