# -*- coding: utf-8 -*-
"""Generate a reviewable 16x16 glyph-ROM snippet for the top-left mode OSD.

This reuses font2verilog.py's rendering path but never rewrites font_rom.v,
so the existing scrolling-subtitle glyph package remains byte-for-byte intact.
The generated text is intentionally not a project .v file: the actual module is
embedded in osd_engine.v so an already-open TD GUI cannot drop it from Active Syn.
"""

import os
import font2verilog as base


# Keep this order synchronized with osd_engine.v's status_glyph_sel table.
# 0/1 and the middle dot are the white prefix; glyphs 3..16 are yellow titles.
CHARS = ["0", "1", "·",
         "直", "接", "切", "换",
         "淡", "入", "出",
         "横", "向", "黑", "幕",
         "布", "开", "合"]
OUT_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                        "..", "mode_status_font_rom.generated.txt")


def main():
    font_name, font_path = base.find_font("思源黑体")
    base.DIGIT_CHARS.update({"0", "1"})

    glyphs = []
    for ch in CHARS:
        if ch == "·":
            # The common font renderer crops every glyph to its ink box before
            # scaling.  That is useful for Han characters but turns a middle
            # dot into a full-cell disc.  Keep this punctuation as a centered
            # 3x3 mark so it remains visibly subordinate to the mode digits.
            rows = [0] * 16
            rows[7] = 0x01C0
            rows[8] = 0x01C0
            rows[9] = 0x01C0
        else:
            rows = base.render_char(ch, font_path, base.FONT_WEIGHT,
                                    base.THRESHOLD, False, False)
        glyphs.append(base.fmt_verilog(rows))

    # glyph 0 occupies the least-significant 256 bits, matching font_rom.v.
    packed = "_".join(reversed(glyphs))
    glyph_count = len(CHARS)
    total_bits = glyph_count * 256
    select_bits = (glyph_count - 1).bit_length()
    glyph_map = " ".join("%d%s" % (index, ch)
                         for index, ch in enumerate(CHARS))
    text = f"""//====================================================
// mode_status_font_rom — glyph ROM for \"00 · 直接切换\" and the other titles
// Generated by python/mode_status_font2verilog.py using the same 64x64
// grayscale -> LANCZOS -> 16x16 -> threshold pipeline as font_rom.v.
// Glyph map: {glyph_map}
// Existing scrolling-subtitle FONT_ALL is not modified.
//====================================================
module mode_status_font_rom(
    input  wire [{select_bits - 1}:0] glyph_sel,
    input  wire [3:0] row,
    input  wire [3:0] col,
    output wire       pixel_on
);

localparam [{total_bits - 1}:0] MODE_FONT_ALL = {total_bits}'h{packed};
wire [255:0] glyph_bits = MODE_FONT_ALL[{{glyph_sel, 8'b00000000}} +: 256];
wire [15:0] glyph_row = glyph_bits[{{row, 4'b0000}} +: 16];
assign pixel_on = (glyph_sel < {select_bits}'d{glyph_count}) ? glyph_row[15 - col] : 1'b0;

endmodule
"""
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)
    print("font=%s path=%s" % (font_name, font_path))
    print("wrote=%s glyphs=%d" % (os.path.abspath(OUT_PATH), len(CHARS)))


if __name__ == "__main__":
    main()
